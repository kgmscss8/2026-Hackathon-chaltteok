import { describe, expect, it } from 'vitest';
import { MASK, maskPII } from '../lib/masking.js';

describe('maskPII — 가려야 하는 것', () => {
  const cases: [string, string][] = [
    ['주민등록번호 하이픈', '제 번호는 900101-1234567 이에요'],
    ['주민등록번호 공백', '900101 2234567'],
    ['주민등록번호 붙여 씀', '9001012234567'],
    ['2000년대생 주민등록번호', '050505-3123456'],
    ['외국인등록번호', '900101-5123456'],
    ['휴대폰 하이픈', '010-1234-5678로 연락 주세요'],
    ['휴대폰 붙여 씀', '01012345678'],
    ['휴대폰 공백', '010 1234 5678'],
    ['휴대폰 점', '010.1234.5678'],
    ['옛 휴대폰 3자리 국번', '011-123-4567'],
    ['서울 일반 전화', '02-123-4567'],
    ['서울 일반 전화 4자리', '02-1234-5678'],
    ['경기 일반 전화', '031-123-4567'],
    ['괄호 지역번호', '(02) 1234-5678'],
    ['인터넷 전화', '070-1234-5678'],
  ];
  for (const [name, input] of cases) {
    it(name, () => {
      const out = maskPII(input);
      expect(out).toContain(MASK);
      expect(out).not.toMatch(/\d{7,}/);
    });
  }

  it('한 문장에 여러 개가 있으면 모두 가린다', () => {
    expect(maskPII('엄마 주민번호 400101-2123456, 제 폰 010-9876-5432')).toBe(
      `엄마 주민번호 ${MASK}, 제 폰 ${MASK}`,
    );
  });

  it('가린 뒤에도 앞뒤 문장은 그대로 둔다', () => {
    expect(maskPII('연락처는 010-1234-5678 입니다.')).toBe(`연락처는 ${MASK} 입니다.`);
  });
});

describe('maskPII — 가리면 안 되는 것', () => {
  const keep = [
    '보건복지상담센터 129에 전화했어요',
    '정부민원안내콜센터 110',
    '국민연금공단 1355',
    '긴급하면 119, 112',
    '고객센터 1588-1234',
    '2026년 11월 21일까지 내야 해요',
    '2026-11-21 마감이에요',
    '기초연금 30만원',
    '101동 1203호에 살아요',
    '우편번호 54870',
    '',
  ];
  for (const text of keep) {
    it(`"${text}"`, () => {
      expect(maskPII(text)).toBe(text);
    });
  }
});
