export const DICTIONARIES: Record<Language, Dictionary> = { ko, en, vi };

/** 문구 꺼내기. {name} 자리에 vars 값을 넣는다 */
export function t(
  lang: Language,
  key: MessageKey,
  vars: Record<string, string | number> = {},
): string {
  const text = DICTIONARIES[lang][key] ?? ko[key];
  return text.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

export type ErrorKey = ErrorCode | 'NOT_HEARD';
export const errorText = (lang: Language, code: ErrorKey) => t(lang, `error.${code}` as MessageKey);
export const recorderErrorText = (lang: Language, code: RecorderErrorCode) =>
  t(lang, `rec.${code}` as MessageKey);
export const slotLabel = (lang: Language, key: SlotKey) => t(lang, `slot.${key}` as MessageKey);

